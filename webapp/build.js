'use strict';
// Builds the SaveMind web dashboard into docs/ (served by GitHub Pages):
// the shared interface plus the Mac backend bundled for the browser.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ui = path.join(root, 'savemind', 'src', 'main', 'assets', 'web');
const backend = path.join(root, 'desktop', 'backend');
const out = path.join(root, 'docs');
const version = require(path.join(root, 'desktop', 'package.json')).version;

// Browser stand-ins for the few Node modules the backend uses. Storage is one localStorage entry.
const shims = {
  fs: `const KEY = 'savemind-web';
    module.exports = {
      readFileSync() { const v = localStorage.getItem(KEY); if (v == null) throw new Error('none'); return v; },
      writeFileSync(f, text) { localStorage.setItem(KEY, text); },
      renameSync() {}, mkdirSync() {}
    };`,
  path: `module.exports = { join: (...p) => p.filter(Boolean).join('/') };`,
  crypto: `module.exports = { randomUUID: () => crypto.randomUUID() };`
};

const modules = {
  './store': fs.readFileSync(path.join(backend, 'store.js'), 'utf8'),
  './sync': fs.readFileSync(path.join(backend, 'sync.js'), 'utf8'),
  './bridge': fs.readFileSync(path.join(backend, 'bridge.js'), 'utf8'),
  './urlutil': fs.readFileSync(path.join(backend, 'urlutil.js'), 'utf8'),
  './claude': fs.readFileSync(path.join(backend, 'claude.js'), 'utf8'),
  './prompt': fs.readFileSync(path.join(backend, 'prompt.js'), 'utf8'),
  './sync-config': fs.readFileSync(path.join(root, 'desktop', 'sync-config.js'), 'utf8'),
  fs: shims.fs, path: shims.path, crypto: shims.crypto,
  './entry': fs.readFileSync(path.join(__dirname, 'entry.js'), 'utf8')
};

let bundle = '// SaveMind web ' + version + ' (generated by webapp/build.js; do not edit)\n(function () {\n'
  + 'var SM_WEB_VERSION = ' + JSON.stringify(version) + ';\nvar defs = {}, cache = {};\n'
  + 'function require(n) { if (cache[n]) return cache[n].exports; var m = cache[n] = { exports: {} }; defs[n](m, m.exports, require); return m.exports; }\n';
for (const [name, src] of Object.entries(modules)) {
  bundle += 'defs[' + JSON.stringify(name) + '] = function (module, exports, require) {\n' + src + '\n};\n';
}
bundle += 'require("./entry");\n})();\n';

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(ui, out, { recursive: true });
fs.writeFileSync(path.join(out, 'sm-web.js'), bundle);

const sync = require(path.join(root, 'desktop', 'sync-config.js'));
let html = fs.readFileSync(path.join(ui, 'index.html'), 'utf8');
html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/,
  `<meta http-equiv="Content-Security-Policy" content="default-src 'self'; img-src 'self' https: data:; style-src 'self' 'unsafe-inline'; script-src 'self'; font-src 'self'; connect-src ${sync.url}">`)
  .replace('<title>SaveMind</title>', '<title>SaveMind</title>\n  <meta name="description" content="Your saved opportunities, deadlines and workload on one screen.">\n  <meta name="theme-color" content="#16181D">\n  <meta name="apple-mobile-web-app-capable" content="yes">\n  <meta name="apple-mobile-web-app-title" content="SaveMind">')
  .replace('<script src="app.js"></script>', '<script src="sm-web.js"></script>\n  <script src="app.js"></script>');
if (!html.includes('sm-web.js') || !html.includes(sync.url)) throw new Error('index.html template changed');
fs.writeFileSync(path.join(out, 'index.html'), html);
fs.writeFileSync(path.join(out, '.nojekyll'), '');
console.log('Built web dashboard', version, 'into', out);
